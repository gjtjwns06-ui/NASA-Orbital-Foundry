/** Reproducible GMAT R2026a point-mass cross-check. No runtime server or GUI. */
import { mkdir, readFile, writeFile, copyFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const project = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const root = path.resolve(project, '..');
const gmat = path.resolve(process.env.GMAT_HOME || path.join(root, '.tools/gmat'));
const bin = path.join(gmat, 'bin');
const evidence = path.join(project, 'tools/gmat/evidence');
const scripts = path.join(project, 'tools/gmat/scripts');
const published = path.join(project, 'public/data/gmat');
const physics = await import(pathToFileURL(path.join(project, 'src/sim/physics.ts')));
const { earthStateAt, marsStateAt, circularState, EARTH_MU, MARS_MU, EARTH_RADIUS_KM, MARS_RADIUS_KM } = physics;
const base = { altitudeKm:600, inclinationDeg:51.6, burnTime:1200, progradeMps:0, radialMps:0, normalMps:0, periapsisAltitudeKm:1000, bPlaneAngleDeg:0, operations:[] };
export const cases = [
  { id:'earth-reference', body:'Earth', duration:86400, plan:{...base} },
  { id:'earth-low-inclination', body:'Earth', duration:86400, plan:{...base,altitudeKm:400,inclinationDeg:28.5} },
  { id:'earth-polar', body:'Earth', duration:86400, plan:{...base,altitudeKm:900,inclinationDeg:97.6} },
  { id:'earth-three-axis-burn', body:'Earth', duration:86400, plan:{...base,progradeMps:80,radialMps:20,normalMps:15} },
  { id:'mars-reference', body:'Mars', duration:18000, plan:{...base} },
  { id:'mars-low-tilted', body:'Mars', duration:18000, plan:{...base,periapsisAltitudeKm:500,bPlaneAngleDeg:45} },
  { id:'mars-high-polar', body:'Mars', duration:18000, plan:{...base,periapsisAltitudeKm:2500,bPlaneAngleDeg:90} },
  { id:'mars-distant-tilted', body:'Mars', duration:18000, plan:{...base,periapsisAltitudeKm:6000,bPlaneAngleDeg:-45} },
];
const sha = data => createHash('sha256').update(data).digest('hex');
const slash = value => value.replaceAll('\\','/');
const number = x => Number(x).toPrecision(17);
const distance = (a,b) => Math.hypot(...a.map((x,i)=>x-b[i]));
const stateAt = (c,t) => c.body==='Earth' ? earthStateAt(c.plan,t) : marsStateAt(c.plan,t);
const epoch = '15 Nov 2026 00:00:00.000';
const spacing = 60;

function makeScript(c) {
  const state = stateAt(c,0), frame = `${c.body}MJ2000Eq`;
  const fields = ['X','Y','Z','VX','VY','VZ'];
  const vector = [...state.positionKm,...state.velocityKmS];
  const burn = c.body==='Earth' && Math.hypot(c.plan.progradeMps,c.plan.radialMps,c.plan.normalMps)>0;
  const line = [
    '% Orbital Foundry independent point-mass validation. Generated by tools/gmat/validate.mjs.',
    '% Units km, km/s, seconds. TAI epoch fixed; MJ2000Eq right-handed axes.',
    `% Case ${c.id}; validation only: no fuel/resource certification.`,
    `${c.body}.Mu = ${c.body==='Earth'?EARTH_MU:MARS_MU};`,
    `${c.body}.EquatorialRadius = ${c.body==='Earth'?EARTH_RADIUS_KM:MARS_RADIUS_KM};`,
  ];
  if(c.body==='Mars') line.push('Create CoordinateSystem MarsMJ2000Eq;','MarsMJ2000Eq.Origin = Mars;','MarsMJ2000Eq.Axes = MJ2000Eq;');
  line.push('Create Spacecraft Probe;', 'Probe.DateFormat = TAIGregorian;', `Probe.Epoch = '${epoch}';`, `Probe.CoordinateSystem = ${frame};`, 'Probe.DisplayStateType = Cartesian;');
  fields.forEach((f,i)=>line.push(`Probe.${f} = ${number(vector[i])};`));
  line.push('Probe.DryMass = 100;','Create ForceModel PointMass;',`PointMass.CentralBody = ${c.body};`,`PointMass.PrimaryBodies = {};`,`PointMass.PointMasses = {${c.body}};`,'PointMass.Drag = None;','PointMass.SRP = Off;','PointMass.RelativisticCorrection = Off;',
    'Create Propagator Prop;','Prop.FM = PointMass;','Prop.Type = PrinceDormand78;','Prop.InitialStepSize = 10;','Prop.Accuracy = 1e-12;','Prop.MinStep = 0.000001;','Prop.MaxStep = 60;','Prop.MaxStepAttempts = 100;','Prop.StopIfAccuracyIsViolated = true;',
    'Create ReportFile States;',`States.Filename = '${c.id}.csv';`,'States.Precision = 17;','States.WriteHeaders = false;','States.FixedWidth = false;',"States.Delimiter = ',';",'States.WriteReport = true;');
  if(burn) {
    const s = circularState(c.plan.altitudeKm,c.plan.inclinationDeg,c.plan.burnTime);
    const r=physics.normalize(s.positionKm), p=physics.normalize(s.velocityKmS), n=physics.normalize(physics.cross(r,p));
    const dv = r.map((_,i)=>(r[i]*c.plan.radialMps+p[i]*c.plan.progradeMps+n[i]*c.plan.normalMps)/1000);
    line.push('Create ImpulsiveBurn Correction;',`Correction.CoordinateSystem = ${frame};`,'Correction.DecrementMass = false;',...dv.map((v,i)=>`Correction.Element${i+1} = ${number(v)};`));
  }
  line.push('BeginMissionSequence;');
  const report = `Report States Probe.ElapsedSecs ${fields.map(f=>`Probe.${frame}.${f}`).join(' ')};`;
  line.push(report);
  for(let t=spacing;t<=c.duration;t+=spacing){
    // GMAT's ElapsedSecs stop condition resets at each Propagate command; report parameter does not.
    line.push(`Propagate Prop(Probe) {Probe.ElapsedSecs = ${spacing}};`,report);
    // Report the pre-burn endpoint at t_b, then apply the velocity discontinuity.
    if(burn && t===c.plan.burnTime)line.push('Maneuver Correction(Probe);');
  }
  return line.join('\n')+'\n';
}

await Promise.all([mkdir(evidence,{recursive:true}),mkdir(scripts,{recursive:true}),mkdir(published,{recursive:true})]);
const originalStartup = await readFile(path.join(bin,'gmat_startup_file.txt'),'utf8');
// These tests require only core spacecraft, point-mass force, propagator, report and burn classes.
// Disable optional GUI/Python/Matlab interfaces so local authoring never opens a window.
let startup = originalStartup.replace(/^PLUGIN\s*=.*$/gm, x=>'# validation excludes optional '+x)
  .replace(/^ROOT_PATH\s*=.*$/m,`ROOT_PATH = ${slash(gmat)}/`)
  .replace(/^OUTPUT_PATH\s*=.*$/m,`OUTPUT_PATH = ${slash(evidence)}/`);
const startupFile = path.join(bin,'orbital_foundry_startup.txt');
await writeFile(startupFile,startup);
const executable = path.join(bin,process.platform==='win32'?'GmatConsole.exe':'GmatConsole');
const executableSha256 = sha(await readFile(executable));
const summary = {
  schemaVersion:1, generator:'tools/gmat/validate.mjs', generatedAtUtc:new Date().toISOString(),
  gmatRelease:'R2026a', executableSha256, epoch:{value:'2026-11-15T00:00:00.000',scale:'TAI'},
  model:'central-body point mass only; no J2, drag, SRP, third-body gravity or relativity',
  axes:'MJ2000Eq, right-handed X/Y equatorial plane and Z north; central-body-relative origin',
  units:{position:'km',velocity:'km/s',time:'s',mu:'km^3/s^2'},
  sampleSeconds:spacing, tolerance:{maxPositionErrorKm:0.01,maxVelocityErrorKmS:0.00001},
  limitations:['Mars cases validate a local idealized unpowered flyby, not an Earth-to-Mars transfer.', 'No real Sun/Earth/Mars ephemeris, navigation covariance, launch window, spacecraft resource or communications validation.', 'Mars asymptotic Sun-relative comparison uses an educational prescribed planet velocity in the game, not GMAT ephemerides.'],
  cases:[],
};
for(const c of cases){
  const script = makeScript(c), scriptFile=path.join(scripts,c.id+'.script');
  await writeFile(scriptFile,script);
  const start = performance.now();
  const result = spawnSync(executable,['--startup_file',startupFile,'--run',scriptFile,'--verbose','off','--logfile',path.join(evidence,c.id+'.gmat.log')],{cwd:bin,encoding:'utf8',windowsHide:true,timeout:120000,maxBuffer:8*1024*1024});
  const stdout = (result.stdout||'')+(result.stderr||'');
  await writeFile(path.join(evidence,c.id+'.console.txt'),stdout);
  if(result.error || result.status!==0 || !stdout.includes('GMAT Integration test (Console version) successful!')) {
    throw new Error(`${c.id}: actual GMAT failed (${result.status}): ${result.error||stdout.slice(-6000)}`);
  }
  const csv = await readFile(path.join(evidence,c.id+'.csv'),'utf8');
  const rows = csv.trim().split(/\r?\n/).map(line=>line.split(',').map(Number));
  if(rows.length!==c.duration/spacing+1 || rows.some(row=>row.length!==7||row.some(v=>!Number.isFinite(v))))throw new Error(`${c.id}: invalid/missing GMAT samples`);
  let maxPositionErrorKm=0,maxVelocityErrorKmS=0;
  for(const [t,...state] of rows){
    // The event has an exact requested epoch; GMAT may report a sub-microsecond stop-time residual.
    const requestedTime=Math.round(t/spacing)*spacing;
    if(Math.abs(t-requestedTime)>0.001)throw new Error(`${c.id}: sample time tolerance exceeded: ${t}`);
    const expected=stateAt(c,requestedTime);
    maxPositionErrorKm=Math.max(maxPositionErrorKm,distance(state.slice(0,3),expected.positionKm));
    maxVelocityErrorKmS=Math.max(maxVelocityErrorKmS,distance(state.slice(3),expected.velocityKmS));
  }
  const pass=maxPositionErrorKm<=summary.tolerance.maxPositionErrorKm&&maxVelocityErrorKmS<=summary.tolerance.maxVelocityErrorKmS;
  const detail={...c,origin:c.body,frame:`${c.body}MJ2000Eq`,mu:c.body==='Earth'?EARTH_MU:MARS_MU,initialState:stateAt(c,0),sampleCount:rows.length,maxPositionErrorKm,maxVelocityErrorKmS,pass,runMs:Math.round(performance.now()-start),scriptSha256:sha(script),csvSha256:sha(csv)};
  summary.cases.push(detail);
  await writeFile(path.join(published,c.id+'.json'),JSON.stringify({schemaVersion:1,id:c.id,epoch:summary.epoch,frame:detail.frame,model:summary.model,units:summary.units,mu:detail.mu,plan:c.plan,columns:['t','x','y','z','vx','vy','vz'],samples:rows}));
  console.log(`${c.id}: ${pass?'PASS':'FAIL'}, ${rows.length} states, position ${maxPositionErrorKm.toExponential(3)} km, velocity ${maxVelocityErrorKmS.toExponential(3)} km/s`);
}
summary.pass=summary.cases.every(c=>c.pass);
await writeFile(path.join(published,'validation-summary.json'),JSON.stringify(summary,null,2)+'\n');
await copyFile(path.join(published,'validation-summary.json'),path.join(evidence,'validation-summary.json'));
if(!summary.pass)process.exitCode=1;
