import {test,expect} from '@playwright/test';
import {mkdirSync,writeFileSync} from 'node:fs';
import {join} from 'node:path';
const out=join(process.cwd(),'tests/browser/artifacts/solar-renderer',process.env.SOLAR_RENDERER_RUN_ID??'r2');mkdirSync(out,{recursive:true});
test('physical mounted lens renders, aims, zooms, captures and follows a moving encounter',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
 await page.goto('/tests/browser/fixtures/solar-renderer.html');await page.waitForFunction(()=>!!(window as any).rendererFixture);
 await page.waitForFunction(()=>{const s=(window as any).rendererFixture.renderer;return s.scene.background?.isTexture;});
 await page.screenshot({path:join(out,'01-chase.png')});
 await page.locator('#instrument').click();await page.screenshot({path:join(out,'02-instrument-context.png')});
 const pose=await page.evaluate(()=>(window as any).rendererFixture.renderer.getInstrumentPose());
 const centreBefore=await page.evaluate(()=>(window as any).rendererFixture.renderer.projectBody('mars'));
 await page.mouse.move(720,460);await page.mouse.down();await page.mouse.move(820,510,{steps:10});await page.mouse.up();
 const moved=await page.evaluate(()=>(window as any).rendererFixture.renderer.getInstrumentPose());
 expect(Math.hypot(...moved.aimDirection.map((v:number,i:number)=>v-pose.aimDirection[i]))).toBeGreaterThan(.05);
 await page.mouse.wheel(0,-1000);
 await expect.poll(async()=>page.evaluate(()=>(window as any).rendererFixture.renderer.getInstrumentPose().fovDeg)).toBeLessThan(pose.fovDeg);
 await page.screenshot({path:join(out,'03-pointed-detail.png')});
 await page.locator('#capture').click();await page.waitForFunction(()=>!!(window as any).rendererFixture.capture);
 const capture=await page.evaluate(()=>(window as any).rendererFixture.capture);
 expect(capture.imageDataUrl).toMatch(/^data:image\/jpeg;base64,/);expect(capture.imageDataUrl.length).toBeGreaterThan(5000);expect(capture.imageDataUrl.length).toBeLessThan(200000);
 writeFileSync(join(out,'instrument-capture.jpg'),Buffer.from(capture.imageDataUrl.split(',')[1],'base64'));
 await page.locator('#advance').click();const centreAfter=await page.evaluate(()=>(window as any).rendererFixture.renderer.projectBody('mars'));
 expect(Math.hypot(centreAfter.x-centreBefore.x,centreAfter.y-centreBefore.y)).toBeGreaterThan(20);
 await page.locator('#cruise').click();await page.screenshot({path:join(out,'04-cruise.png')});
 await page.locator('#map').click();await page.screenshot({path:join(out,'05-map.png')});
 writeFileSync(join(out,'evidence.json'),JSON.stringify({kind:'isolated-renderer-component-test, not an integrated user journey',errors,pose,moved,capturePose:capture.pose,captureBytes:capture.imageDataUrl.length,centreBefore,centreAfter},null,2));
 expect(errors).toEqual([]);
});
